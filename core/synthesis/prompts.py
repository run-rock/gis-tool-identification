"""
Prompt模板和Pydantic模型定义

整合了原有的prompt模板，用于场景生成、案例生成、案例验证和案例修正
"""

from pydantic import BaseModel, Field
from typing import List
from enum import IntEnum


# ============================================================================
# Pydantic模型定义
# ============================================================================

class Scenario(BaseModel):
    """场景模型"""
    name: str = Field(description="Geospatial analysis scenario name")
    description: str = Field(description="Geospatial analysis scenario overview")
    tool_use: str = Field(description="How the tool works in this scenario")


class ScenarioList(BaseModel):
    """场景列表模型"""
    scenarios: List[Scenario] = Field(description="Five classic geospatial analysis scenarios corresponding to this tool")


class GeneratedCase(BaseModel):
    """生成的案例模型"""
    case: str = Field(description="Generated GIS task query that is clearly defined and realistically feasible")


class JudgeResult(IntEnum):
    """判断结果枚举"""
    CANNOT_SOLVE = 0  # 不能独立解决
    CAN_SOLVE = 1     # 能独立解决
    REQUIRES_COMBINATION = 2  # 需要别的工具或简单操作进行辅助


class CaseCheck(BaseModel):
    """案例检查结果模型"""
    judge: JudgeResult = Field(description="Judgment result: 1 means can solve independently, 0 means cannot solve independently, 2 means needs other tools or simple operations for assistance")
    evidence: str = Field(description="Justification for the judgment")


class RevisedCase(BaseModel):
    """修正后的案例模型"""
    revised_case: str = Field(description="Optimized case after addressing the criticisms")


# ============================================================================
# Prompt模板定义
# ============================================================================


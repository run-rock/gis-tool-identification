GENERATE_CASE_FROM_SCENARIO_PROMPT = """

You will be given a GIS tool. Carefully read and understand the tool's name and description, as well as the scenario information. Your task is to generate a GIS task query that is "clearly defined and realistically feasible" under this scenario.

Key Points:

Hide tool name: Do not mention the tool explicitly. Convert technical terms such as "buffer," "overlay," or "clip" into plain, non-technical language that expresses the intention (e.g., "find the area within a certain distance from a location").

Tool must solve task independently: The task must be solvable by this tool alone. Carefully observe the tool's capability boundaries, generate a task within those boundaries, and fully utilize its functions.

Complete structure: Include project or research background, the available data (type, format, source), and the objective. These should be expressed naturally in the query, without explicitly using labels like "background," "data," or "objective."

Non-technical expression: The query should represent a clear, non-specialized geospatial analysis need that the tool can address. Do not describe the specific operations of the tool. Replace professional GIS concepts and vocabulary with plain language.

Data-type matching: Match the input type the tool accepts, and mention the corresponding data in the query (e.g., "a .shp file containing building footprints").

Concise and formal language: The task description should be clear, concise, and expressed in a formal tone.

Tool information:
{gis_tool}
Scenario information:
{scenario}
Output format:
{format_instructions}

"""


